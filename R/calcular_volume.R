# Cálculo do volume das presas
# ============================================================

calcular_volume <- function(dados) {
  
  # ----------------------------------------------------------
  # Calcular volume
  # Fórmula:
  # V = (pi / 6) × largura² × comprimento
  # ----------------------------------------------------------
  
  dados$V <- (
    4.18
  ) * (
    dados$largura/2)^2*
    (dados$comprimento/2)
  
  
  # ----------------------------------------------------------
  # Retornar dados
  # ----------------------------------------------------------
  
  return(dados)
}